-- Grundschema eines Realms: Admin-Flag, Avatar in der DB,
-- Einstellungen (Einladungscode), Upload-Schlüssel je Freigabe, Änderungsprotokoll für Polling.
CREATE TABLE IF NOT EXISTS events (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, year INTEGER NOT NULL, startDate TEXT NOT NULL,
  days INTEGER NOT NULL, isCurrent INTEGER NOT NULL DEFAULT 0, createdAt INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS members (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, motto TEXT NOT NULL DEFAULT '', color TEXT NOT NULL,
  hasAvatar INTEGER NOT NULL DEFAULT 0, createdAt INTEGER NOT NULL, password TEXT NOT NULL DEFAULT '',
  isAdmin INTEGER NOT NULL DEFAULT 0, avatar BLOB, avatarUpdatedAt INTEGER
);
CREATE TABLE IF NOT EXISTS auth_tokens (
  tokenHash TEXT PRIMARY KEY, memberId INTEGER NOT NULL, device TEXT NOT NULL DEFAULT '', createdAt INTEGER NOT NULL, lastUsedAt INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_auth_tokens_member ON auth_tokens(memberId);
CREATE TABLE IF NOT EXISTS games (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', steamUrl TEXT NOT NULL DEFAULT '',
  steamAppId INTEGER, imageUrl TEXT NOT NULL DEFAULT '', players TEXT NOT NULL DEFAULT '', addedById INTEGER,
  selectedForNext INTEGER NOT NULL DEFAULT 0, createdAt INTEGER NOT NULL, sharePath TEXT NOT NULL DEFAULT '', shareId INTEGER
);
CREATE TABLE IF NOT EXISTS shares (
  id INTEGER PRIMARY KEY AUTOINCREMENT, path TEXT NOT NULL, addedById INTEGER, lastScanAt INTEGER, lastError TEXT NOT NULL DEFAULT '',
  lastCount INTEGER NOT NULL DEFAULT 0, knownFolders TEXT NOT NULL DEFAULT '', uploadKey TEXT NOT NULL, createdAt INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
  id INTEGER PRIMARY KEY AUTOINCREMENT, gameId INTEGER NOT NULL, eventId INTEGER NOT NULL, startedAt INTEGER NOT NULL,
  endedAt INTEGER, chosenBy TEXT NOT NULL DEFAULT 'manual', note TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_sessions_game ON sessions(gameId);
CREATE INDEX IF NOT EXISTS idx_sessions_event ON sessions(eventId);
CREATE TABLE IF NOT EXISTS session_participants (sessionId INTEGER NOT NULL, memberId INTEGER NOT NULL, PRIMARY KEY (sessionId, memberId));
CREATE TABLE IF NOT EXISTS suggestions (
  id INTEGER PRIMARY KEY AUTOINCREMENT, scope TEXT NOT NULL, title TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
  steamUrl TEXT NOT NULL DEFAULT '', steamAppId INTEGER, imageUrl TEXT NOT NULL DEFAULT '', authorId INTEGER, adoptedGameId INTEGER, createdAt INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS suggestion_votes (suggestionId INTEGER NOT NULL, memberId INTEGER NOT NULL, value INTEGER NOT NULL, PRIMARY KEY (suggestionId, memberId));
CREATE TABLE IF NOT EXISTS suggestion_comments (
  id INTEGER PRIMARY KEY AUTOINCREMENT, suggestionId INTEGER NOT NULL, authorId INTEGER, text TEXT NOT NULL, createdAt INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS forum_posts (
  id INTEGER PRIMARY KEY AUTOINCREMENT, authorId INTEGER, title TEXT NOT NULL, body TEXT NOT NULL, pinned INTEGER NOT NULL DEFAULT 0, createdAt INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS forum_comments (
  id INTEGER PRIMARY KEY AUTOINCREMENT, postId INTEGER NOT NULL, authorId INTEGER, body TEXT NOT NULL, createdAt INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS attendance (eventId INTEGER NOT NULL, memberId INTEGER NOT NULL, day INTEGER NOT NULL, PRIMARY KEY (eventId, memberId, day));
CREATE TABLE IF NOT EXISTS expenses (
  id INTEGER PRIMARY KEY AUTOINCREMENT, eventId INTEGER NOT NULL, title TEXT NOT NULL, amountCents INTEGER NOT NULL, paidById INTEGER NOT NULL,
  day INTEGER, note TEXT NOT NULL DEFAULT '', createdAt INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS expense_shares (expenseId INTEGER NOT NULL, memberId INTEGER NOT NULL, PRIMARY KEY (expenseId, memberId));
CREATE TABLE IF NOT EXISTS payments (
  id INTEGER PRIMARY KEY AUTOINCREMENT, eventId INTEGER NOT NULL, fromId INTEGER NOT NULL, toId INTEGER NOT NULL, amountCents INTEGER NOT NULL, createdAt INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS equipment (
  id INTEGER PRIMARY KEY AUTOINCREMENT, eventId INTEGER NOT NULL, name TEXT NOT NULL, category TEXT NOT NULL, quantity INTEGER NOT NULL DEFAULT 1,
  note TEXT NOT NULL DEFAULT '', bringerId INTEGER, done INTEGER NOT NULL DEFAULT 0, createdAt INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS polls (
  id INTEGER PRIMARY KEY AUTOINCREMENT, eventId INTEGER NOT NULL, open INTEGER NOT NULL DEFAULT 1, winnerGameId INTEGER, createdAt INTEGER NOT NULL, closedAt INTEGER
);
CREATE TABLE IF NOT EXISTS poll_votes (pollId INTEGER NOT NULL, memberId INTEGER NOT NULL, gameId INTEGER NOT NULL, PRIMARY KEY (pollId, memberId));
CREATE TABLE IF NOT EXISTS xp_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT, memberId INTEGER NOT NULL, type TEXT NOT NULL, refId INTEGER NOT NULL, amount INTEGER NOT NULL, createdAt INTEGER NOT NULL,
  UNIQUE (type, refId, memberId)
);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
-- Letzte Änderung je Thema, damit Clients ohne WebSocket nachfragen können
CREATE TABLE IF NOT EXISTS changes (topic TEXT PRIMARY KEY, ts INTEGER NOT NULL);
